/* gen-deploy-headers.mjs — write the static-host deploy configs.

   Reads config/security-headers.mjs (the single definition, also used by
   next.config.ts) and emits:

     public/_headers   Netlify / Cloudflare Pages
     netlify.toml      Netlify build + headers + SPA-less 404
     vercel.json       Vercel static deploy

   Run:  node scripts/gen-deploy-headers.mjs

   The three files are GENERATED — edit config/security-headers.mjs and
   re-run this script instead of touching them.                             */

import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SECURITY_HEADERS } from '../config/security-headers.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BANNER = 'GENERATED by scripts/gen-deploy-headers.mjs — edit config/security-headers.mjs instead.';

/* ---------- public/_headers (Netlify, Cloudflare Pages) ---------- */
const headersFile =
  `# ${BANNER}\n\n/*\n` +
  SECURITY_HEADERS.map((h) => `  ${h.key}: ${h.value}\n`).join('') +
  `\n# Fingerprint-free assets: revalidate, but allow a short cache.\n` +
  `/assets/*\n  Cache-Control: public, max-age=86400, must-revalidate\n` +
  `/mu/*\n  Cache-Control: public, max-age=86400, must-revalidate\n`;

writeFileSync(resolve(ROOT, 'public/_headers'), headersFile);

/* ---------- netlify.toml ---------- */
const toml =
  `# ${BANNER}\n\n` +
  `[build]\n  publish = "public"\n  command = ""\n\n` +
  `[[headers]]\n  for = "/*"\n  [headers.values]\n` +
  SECURITY_HEADERS.map((h) => `    ${h.key} = ${JSON.stringify(h.value)}\n`).join('') +
  `\n# Serve the styled 404 rather than Netlify's default.\n` +
  `[[redirects]]\n  from = "/*"\n  to = "/404.html"\n  status = 404\n`;

writeFileSync(resolve(ROOT, 'netlify.toml'), toml);

/* ---------- vercel.json ---------- */
const vercel = {
  $schema: 'https://openapi.vercel.sh/vercel.json',
  // NOTE: generated — see config/security-headers.mjs
  headers: [
    {
      source: '/(.*)',
      headers: SECURITY_HEADERS.map((h) => ({ key: h.key, value: h.value })),
    },
  ],
  cleanUrls: false,
  trailingSlash: false,
};

writeFileSync(resolve(ROOT, 'vercel.json'), JSON.stringify(vercel, null, 2) + '\n');

mkdirSync(resolve(ROOT, 'public'), { recursive: true });
console.log('wrote public/_headers, netlify.toml, vercel.json');
console.log(`${SECURITY_HEADERS.length} headers from config/security-headers.mjs`);
